package io.github.monstercouch.homelabrmm.store

import android.content.Context
import android.util.Log
import android.webkit.CookieManager
import android.webkit.WebStorage
import android.webkit.WebViewDatabase
import androidx.datastore.core.DataStore
import androidx.datastore.preferences.core.Preferences
import androidx.datastore.preferences.core.byteArrayPreferencesKey
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.preferencesDataStore
import androidx.webkit.ProfileStore
import androidx.webkit.WebViewFeature
import io.github.monstercouch.homelabrmm.trust.SealedCodec
import io.github.monstercouch.homelabrmm.trust.ServerEntry
import io.github.monstercouch.homelabrmm.trust.ServerList
import io.github.monstercouch.homelabrmm.trust.TrustStore
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.withContext
import java.security.GeneralSecurityException
import javax.crypto.AEADBadTagException

/** One DataStore file holding one key: the sealed blob. */
private val Context.serversDataStore: DataStore<Preferences> by preferencesDataStore(name = "rmm_servers")

/** What a read of the sealed list produced. */
sealed interface ServersState {
    /** The list opened cleanly. May still be empty if the operator forgot everything. */
    data class Ready(val servers: List<ServerEntry>) : ServersState

    /** Nothing has ever been stored. First run. */
    data object Empty : ServersState

    /**
     * The stored bytes could not be opened, so everything was wiped and the
     * operator must re-pair. Never a partial result, never a plaintext read.
     */
    data class Reset(val reason: ResetReason) : ServersState
}

enum class ResetReason {
    /** GCM tag check failed: the blob was altered. */
    TAMPERED,

    /**
     * The AndroidKeyStore key is gone or no longer usable - an uninstall, a
     * signing-identity change, or a device-level key invalidation. Not an
     * attack, same recovery: re-pair, ideally from the exported list.
     */
    KEY_LOST,

    /** The plaintext opened but was not a server list this build understands. */
    UNREADABLE,
}

/**
 * The sealed server list: AES-256-GCM under AndroidKeyStore, one blob, one
 * DataStore key (docs/ANDROID.md §2.3).
 *
 * Blob layout is `[12-byte IV][ciphertext || 16-byte tag]`, produced by
 * [SealedCodec] in `:trust` so the framing and its tamper behaviour are covered
 * by `./gradlew :trust:test` with no device.
 */
class ServerStore(private val context: Context) {

    private val ds get() = context.serversDataStore

    /**
     * Read and open the list.
     *
     * An [AEADBadTagException] means the stored bytes are not the bytes this app
     * wrote. The response is total: wipe the blob, wipe every WebView profile
     * and cookie jar, drop the keystore key, and force re-pairing. There is no
     * fallback to a plaintext read and no "use whatever bytes are there" -
     * either of those turns a detected tamper into an accepted one.
     */
    suspend fun load(): ServersState {
        val blob = ds.data.first()[BLOB] ?: return ServersState.Empty
        val key = try {
            Keystore.getOrCreate()
        } catch (e: GeneralSecurityException) {
            Log.w(TAG, "keystore key unavailable", e)
            wipeEverything()
            return ServersState.Reset(ResetReason.KEY_LOST)
        }

        val plain = try {
            SealedCodec.open(key, blob)
        } catch (e: AEADBadTagException) {
            Log.w(TAG, "sealed server list failed its tag check - wiping")
            wipeEverything()
            return ServersState.Reset(ResetReason.TAMPERED)
        } catch (e: GeneralSecurityException) {
            // A key that exists but can no longer decrypt (invalidated, or
            // generated by a different signing identity) lands here.
            Log.w(TAG, "sealed server list could not be opened", e)
            wipeEverything()
            return ServersState.Reset(ResetReason.KEY_LOST)
        }

        return try {
            ServersState.Ready(ServerList.decode(plain))
        } catch (e: IllegalArgumentException) {
            Log.w(TAG, "server list did not parse", e)
            wipeEverything()
            ServersState.Reset(ResetReason.UNREADABLE)
        }
    }

    /** The list, or an empty list if it could not be opened. */
    suspend fun servers(): List<ServerEntry> = when (val s = load()) {
        is ServersState.Ready -> s.servers
        else -> emptyList()
    }

    /** A [TrustStore] over the current list - the object both pin call sites use. */
    suspend fun trustStore(): TrustStore = TrustStore(servers())

    suspend fun save(entries: List<ServerEntry>) {
        val key = Keystore.getOrCreate()
        val blob = SealedCodec.seal(key, ServerList.encode(entries))
        ds.edit { it[BLOB] = blob }
    }

    /** Insert or replace by id, preserving list order. */
    suspend fun upsert(entry: ServerEntry) {
        val current = servers()
        val i = current.indexOfFirst { it.id == entry.id }
        save(if (i >= 0) current.toMutableList().also { it[i] = entry } else current + entry)
    }

    /**
     * Forget one server: drop the entry, then delete its WebView profile so the
     * cookie jar and local storage of a server the operator no longer trusts do
     * not outlive the pin.
     */
    suspend fun forget(id: String) {
        save(servers().filterNot { it.id == id })
        deleteProfile(id)
    }

    /**
     * The "Export server list" escape hatch. Plain text, url + fp + label, plus
     * a `homelabrmm://pair` link per entry.
     *
     * The keystore key dies with an uninstall or a signing-identity change;
     * re-pairing must not be a scavenger hunt through the console.
     */
    suspend fun exportText(): String = ServerList.exportText(servers())

    /**
     * Drop the sealed blob, every WebView profile, the cookie jar and the
     * keystore key. Called on a failed open, and from "Forget everything".
     */
    suspend fun wipeEverything() {
        runCatching { ds.edit { it.remove(BLOB) } }
        wipeWebData()
        Keystore.delete()
    }

    /**
     * WebView state must be touched on the UI thread: [WebStorage.deleteAllData]
     * and [ProfileStore] are documented as UI-thread APIs, and reaching them
     * from the IO dispatcher is the kind of bug that only shows on one device.
     */
    private suspend fun wipeWebData() = withContext(Dispatchers.Main) {
        runCatching {
            CookieManager.getInstance().removeAllCookies(null)
            CookieManager.getInstance().flush()
        }.onFailure { Log.w(TAG, "cookie wipe failed", it) }
        runCatching { WebStorage.getInstance().deleteAllData() }
            .onFailure { Log.w(TAG, "web storage wipe failed", it) }
        runCatching { WebViewDatabase.getInstance(context).clearHttpAuthUsernamePassword() }
        runCatching {
            if (WebViewFeature.isFeatureSupported(WebViewFeature.MULTI_PROFILE)) {
                val store = ProfileStore.getInstance()
                for (name in store.allProfileNames) {
                    if (name != DEFAULT_PROFILE) runCatching { store.deleteProfile(name) }
                }
            }
        }.onFailure { Log.w(TAG, "profile wipe failed", it) }
    }

    private suspend fun deleteProfile(name: String) = withContext(Dispatchers.Main) {
        runCatching {
            if (WebViewFeature.isFeatureSupported(WebViewFeature.MULTI_PROFILE) && name != DEFAULT_PROFILE) {
                ProfileStore.getInstance().deleteProfile(name)
            }
        }.onFailure { Log.w(TAG, "could not delete profile $name", it) }
    }

    companion object {
        private const val TAG = "ServerStore"

        /** androidx.webkit's name for the profile that cannot be deleted. */
        private const val DEFAULT_PROFILE = "Default"

        private val BLOB = byteArrayPreferencesKey("servers.v1")
    }
}
